"""Catalog snapshot: the reviewed/enriched catalog as a text file that Git can track.

The live database (data/library.db) is runtime data and is not committed. The catalog
knowledge inside it (books, book cards, attribute evidence, authors and their links to books,
relations between books, library sections) is project data, so it is
exported to data/catalog_snapshot.sql, which IS committed.

  backend/venv/bin/python scripts/catalog_snapshot.py export     # DB -> data/catalog_snapshot.sql
  backend/venv/bin/python scripts/catalog_snapshot.py build      # snapshot -> new data/library.db (only if missing)
  backend/venv/bin/python scripts/catalog_snapshot.py check      # does the snapshot match the DB?
  backend/venv/bin/python scripts/catalog_snapshot.py verify     # rebuild the snapshot in memory and compare
                                                                 # schema, row counts and content, table by table

Since 2026-10-09 (audit 2026-10-08) the snapshot also carries the prizes of books and of authors, the
screen adaptations and the library events. NOT exported:
- visitor and staff activity (choices, ratings, reports, visitor notes, staff notes and requests,
  open questions, staff accounts, the audit log, usage counts, confirmations), deleted-book records
  and import history: runtime data;
- book_embeddings (meaning-search vectors): derived data, 18 MB of binary that would more than double
  the text file and change with every edited summary. After `build`, run
  scripts/build_embeddings.py (needs Ollama with bge-m3) to make them again from the books;
- the picture files (data/covers, data/event_images): they are copied by scripts/backup_db.py.
"""
import hashlib
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(ROOT, "data", "library.db")
SNAP = os.path.join(ROOT, "data", "catalog_snapshot.sql")
# Catalog knowledge: the books, their cards and evidence, and (since 2026-10-03) the people behind
# them, the book-to-person links, the relations between books and the library sections. Tables that
# a database does not have yet are skipped, so an older database still exports.
TABLES = [("books", "book_id"), ("book_profiles", "book_id"), ("attribute_evidence", "evidence_id"),
          ("authors", "author_id"), ("book_authors", "book_id, author_id, role"),
          ("book_relations", "relation_id"), ("library_sections", "section_id"),
          ("book_awards", "row_id"), ("author_awards", "row_id"), ("book_adaptations", "row_id"),
          ("events", "event_id")]
# Deliberately left out (see the note at the top); `verify` names them so the gap is never silent.
NOT_EXPORTED = ["book_embeddings"]


def _lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def dump(con):
    lines = ["-- Library Keeper catalog snapshot (generated by scripts/catalog_snapshot.py export)", "BEGIN;"]
    have = []
    for table, key in TABLES:
        row = con.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)).fetchone()
        if row is None:
            continue
        have.append(table)
        lines.append(row[0].strip() + ";")
        cols = [r[1] for r in con.execute(f"PRAGMA table_info({table})")]
        for row in con.execute(f"SELECT {', '.join(cols)} FROM {table} ORDER BY {key}"):
            lines.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(_lit(v) for v in row)});")
    marks = ", ".join("?" * len(have))
    for (sql,) in con.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL "
                              f"AND tbl_name IN ({marks}) ORDER BY name", have):
        lines.append(sql.strip() + ";")
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"


def _norm(sql):
    return " ".join((sql or "").split())


def table_facts(con):
    """{table: (schema, row count, digest of every row in key order)} for the snapshot tables a database has."""
    out = {}
    for table, key in TABLES:
        row = con.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)).fetchone()
        if row is None:
            continue
        cols = [r[1] for r in con.execute(f"PRAGMA table_info({table})")]
        h, n = hashlib.sha1(), 0
        for r in con.execute(f"SELECT {', '.join(cols)} FROM {table} ORDER BY {key}"):
            h.update(repr(tuple(r)).encode("utf-8"))
            n += 1
        idx = sorted(_norm(s) for (s,) in con.execute(
            "SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL AND tbl_name=?", (table,)))
        out[table] = (_norm(row[0]) + " || " + " ; ".join(idx), n, h.hexdigest())
    return out


def rebuild(text):
    """The snapshot text as a fresh in-memory database."""
    con = sqlite3.connect(":memory:")
    con.executescript(text)
    return con


def compare(source, built):
    """-> (report lines, problems). Every snapshot table of `source` must come back from the rebuilt
    snapshot with the same schema (table and indexes), the same number of rows and the same content."""
    a, b = table_facts(source), table_facts(built)
    lines, problems = [], []
    for table, _ in TABLES:
        if table not in a and table not in b:
            lines.append(f"{table}: not in this database (skipped)")
            continue
        if table not in b:
            problems.append(f"{table}: in the database ({a[table][1]} rows) but missing from the snapshot")
            continue
        if table not in a:
            problems.append(f"{table}: in the snapshot ({b[table][1]} rows) but missing from the database")
            continue
        bad = []
        if a[table][0] != b[table][0]:
            bad.append("schema differs")
        if a[table][1] != b[table][1]:
            bad.append(f"rows {a[table][1]} in the database, {b[table][1]} in the snapshot")
        elif a[table][2] != b[table][2]:
            bad.append("same number of rows, different content")
        if bad:
            problems.append(f"{table}: " + "; ".join(bad))
        else:
            lines.append(f"{table}: schema ok, {a[table][1]} rows, content ok")
    for table in NOT_EXPORTED:
        row = source.execute("SELECT name FROM sqlite_master WHERE type='table' AND name=?", (table,)).fetchone()
        if row:
            n = source.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
            lines.append(f"{table}: {n} rows, not exported on purpose (rebuilt by scripts/build_embeddings.py)")
    return lines, problems


def main(cmd):
    if cmd == "verify":
        if not os.path.exists(SNAP):
            print("no snapshot file (run export)")
            return 1
        con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
        built = rebuild(open(SNAP, encoding="utf-8").read())
        ok = built.execute("PRAGMA integrity_check").fetchone()[0]
        lines, problems = compare(con, built)
        con.close()
        built.close()
        for line in lines:
            print("ok   " + line)
        for line in problems:
            print("DIFF " + line)
        if ok != "ok":
            print(f"DIFF rebuilt snapshot fails integrity_check: {ok}")
        good = not problems and ok == "ok"
        print("snapshot rebuilds to the same catalog as the database" if good
              else "snapshot does NOT rebuild to the database's catalog (run export, then verify again)")
        return 0 if good else 1
    if cmd == "export":
        con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
        text = dump(con)
        con.close()
        with open(SNAP, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(SNAP, ROOT)} ({len(text) // 1024} KB)")
        return 0
    if cmd == "check":
        con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
        same = dump(con) == open(SNAP, encoding="utf-8").read()
        con.close()
        print("snapshot matches the database" if same else "snapshot differs from the database (run export)")
        return 0 if same else 1
    if cmd == "build":
        if os.path.exists(DB):
            print("data/library.db already exists; nothing to do")
            return 0
        tmp = DB + ".building"
        if os.path.exists(tmp):
            os.remove(tmp)
        con = sqlite3.connect(tmp)
        con.executescript(open(SNAP, encoding="utf-8").read())
        n = con.execute("SELECT COUNT(*) FROM books").fetchone()[0]
        ok = con.execute("PRAGMA integrity_check").fetchone()[0]
        con.close()
        os.replace(tmp, DB)
        # create the runtime tables the snapshot leaves out (feedback, import_runs) and run migrations
        sys.path.insert(0, os.path.join(ROOT, "backend"))
        import models
        models.init_db()
        tables = [r[0] for r in sqlite3.connect(DB).execute("SELECT name FROM sqlite_master WHERE type='table'")]
        print(f"built data/library.db from snapshot ({n} books, integrity={ok}; tables: {', '.join(sorted(tables))})")
        built = sqlite3.connect(DB)
        for table, (_, rows, _) in table_facts(built).items():
            print(f"  {table}: {rows} rows")
        built.close()
        print("not in the snapshot: meaning-search vectors (run scripts/build_embeddings.py) and the picture "
              "files data/covers, data/event_images (restore them with scripts/restore_db.py --assets-only)")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else ""))
