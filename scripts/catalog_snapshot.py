"""Catalog snapshot: the reviewed/enriched catalog as a text file that Git can track.

The live database (data/library.db) is runtime data and is not committed. The catalog
knowledge inside it (books, book cards, attribute evidence) is project data, so it is
exported to data/catalog_snapshot.sql, which IS committed.

  backend/venv/bin/python scripts/catalog_snapshot.py export     # DB -> data/catalog_snapshot.sql
  backend/venv/bin/python scripts/catalog_snapshot.py build      # snapshot -> new data/library.db (only if missing)
  backend/venv/bin/python scripts/catalog_snapshot.py check      # does the snapshot match the DB?

Visitor feedback and import history are NOT exported (runtime data).
"""
import os
import sqlite3
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(ROOT, "data", "library.db")
SNAP = os.path.join(ROOT, "data", "catalog_snapshot.sql")
TABLES = [("books", "book_id"), ("book_profiles", "book_id"), ("attribute_evidence", "evidence_id")]


def _lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def dump(con):
    lines = ["-- Library Keeper catalog snapshot (generated by scripts/catalog_snapshot.py export)", "BEGIN;"]
    for table, key in TABLES:
        sql = con.execute("SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)).fetchone()[0]
        lines.append(sql.strip() + ";")
        cols = [r[1] for r in con.execute(f"PRAGMA table_info({table})")]
        for row in con.execute(f"SELECT {', '.join(cols)} FROM {table} ORDER BY {key}"):
            lines.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(_lit(v) for v in row)});")
    for (sql,) in con.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL "
                              "AND tbl_name IN ('books','book_profiles','attribute_evidence') ORDER BY name"):
        lines.append(sql.strip() + ";")
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"


def main(cmd):
    if cmd == "export":
        con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
        text = dump(con)
        con.close()
        with open(SNAP, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(SNAP, ROOT)} ({len(text) // 1024} KB)")
        return 0
    if cmd == "check":
        con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
        same = dump(con) == open(SNAP, encoding="utf-8").read()
        con.close()
        print("snapshot matches the database" if same else "snapshot differs from the database (run export)")
        return 0 if same else 1
    if cmd == "build":
        if os.path.exists(DB):
            print("data/library.db already exists; nothing to do")
            return 0
        tmp = DB + ".building"
        if os.path.exists(tmp):
            os.remove(tmp)
        con = sqlite3.connect(tmp)
        con.executescript(open(SNAP, encoding="utf-8").read())
        n = con.execute("SELECT COUNT(*) FROM books").fetchone()[0]
        ok = con.execute("PRAGMA integrity_check").fetchone()[0]
        con.close()
        os.replace(tmp, DB)
        # create the runtime tables the snapshot leaves out (feedback, import_runs) and run migrations
        sys.path.insert(0, os.path.join(ROOT, "backend"))
        import models
        models.init_db()
        tables = [r[0] for r in sqlite3.connect(DB).execute("SELECT name FROM sqlite_master WHERE type='table'")]
        print(f"built data/library.db from snapshot ({n} books, integrity={ok}; tables: {', '.join(sorted(tables))})")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else ""))
